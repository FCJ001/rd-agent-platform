# 分诊 Agent 提示词模板
# 参考天宫医疗版 prompts.py，适配汽车故障诊断领域
# ============================================================

# ── 1. 现象提取（口语 → 现象名 + DTC 码）──────────────────────────────────
EXTRACT_PHENOMENA_PROMPT = """你是汽车研发领域的故障诊断专家。用户描述了一个车辆故障，请从用户的描述中提取标准化现象名称和 DTC 故障码。

用户描述：{user_input}

【已知现象码词汇表】（请尽量匹配，不要编造新现象名）
{phenomenon_vocabulary}

【已知 DTC 故障码格式】字母+数字组合，如 P0A7F、U0100、U0073 等。

请以 JSON 格式输出：
{{
  "phenomena": ["现象名1", "现象名2"],
  "dtc_codes": ["DTC码1"]
}}

要求：
- 只从词汇表中选择最匹配的现象名（1-3 个）
- 如果用户描述中没有提到 DTC 码，dtc_codes 为空数组
- 只输出 JSON，不要解释。"""


# ── 2. 追问生成 ──────────────────────────────────────────────────────────
ASK_DETAILS_PROMPT = """你是汽车研发领域的故障诊断助手。

当前已确认的故障现象：{confirmed_phenomena}
当前候选根因（置信度不足，需要更多信息）：
{candidate_summary}

请生成追问，帮助进一步缩小根因范围。追问方向（每次最多问 2 个方面）：
- 是否伴随其他现象？（如：除了黑屏，是否还有触控失灵、系统卡顿等）
- 是否有 DTC 故障码？（仪表盘是否有报警灯？）
- 发生条件？（冷车/热车、低速/高速、特定操作后）
- 发生频次？（偶发/每次/特定场景）

直接输出追问内容，语气专业但易懂，不要有多余的开场白。"""


# ── 3. 解析用户回答 ──────────────────────────────────────────────────────
PARSE_ANSWER_PROMPT = """你是汽车故障信息提取专家。

我们刚才询问了用户以下问题：
{asked_questions}

用户的回答是：
{user_answer}

你的任务是提取三类信息：

1. **confirmed**：用户明确确认的故障现象（从下面的候选词汇表中选，不要编造）
2. **denied**：用户明确否认的故障现象
3. **dtc_codes**：用户提到的 DTC 故障码（如 U0073、P0A7F、U0100 等字母+数字的故障码格式）

【重要区分规则】
- DTC 故障码（如 "U0073"、"P0A7F"）属于 **dtc_codes**，不要放到 confirmed 或 denied 里
- 即使词汇表里没有某个 DTC 码，只要用户明确说出了，就提取到 dtc_codes
- 现象名（如 "中控屏显示异常"、"系统响应迟滞"）属于 confirmed/denied
- 用户说"没有"、"不是"、"不会" → 放到 denied
- 用户说"是的"、"有"、"经常" → 放到 confirmed

【已知现象码候选】（只从中选择现象名，不要编造）
{phenomenon_vocabulary}

以 JSON 格式输出：
{{
  "confirmed": ["现象A"],
  "denied": ["现象B"],
  "dtc_codes": ["U0073"]
}}

只输出 JSON，不要解释。"""


# ── 4. 诊断结论 ──────────────────────────────────────────────────────────
CONCLUSION_PROMPT = """你是汽车研发领域的故障诊断专家，请根据以下诊断结果生成清晰、专业的诊断结论。

诊断结果：
- 已确认现象：{confirmed_phenomena}
- 已排除现象：{denied_phenomena}
- DTC 故障码：{dtc_codes}
- 主要根因：{primary_cause}（置信度：{confidence:.0%}）
- 候选根因：{suspected_causes}
- 建议责任域：{domain}
- 是否达到追问上限：{force_conclude}

要求：
1. 简要总结故障现象
2. 说明最可能的根因及判断依据
3. 给出处置建议（修复方式 + 预计工时）
4. 列出验证项（如何确认该根因）
5. 如果 force_conclude=True，加上"信息有限，以上诊断仅供参考，建议实车诊断确认"
6. 语气专业、简洁

直接输出结论内容。"""
